#!/usr/bin/env python3
"""Bake the map's structure BSP into C arrays for the PS2 program: src/map_assets.c + src/map_assets.h.

Phase 0 (geometry only): every material's vertices merged into one array, positions, a colour per vertex
(a tint per kind of shader, lit by the packed normal), and the triangles wound counter-clockwise from
outside. Also where the Chief stands: the ground height under MAP_CHIEF_X/Y.

  HALO_MAP (default assets/maps/bloodgulch.map), CHIEF_X, CHIEF_Y, CHIEF_BELOW (env) pick the spot.
"""
import os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from bsp import load_bsp, oriented, ground_height

MAP = os.environ.get('HALO_MAP', os.path.join(HERE, '..', '..', '..', '..', '..', 'assets', 'maps', 'bloodgulch.map'))
OUT = os.path.join(HERE, '..', 'src')
# open ground 12 wu in front of the base whose flag is at (40.2, -79.1): flat, with room to orbit
CHIEF_X = float(os.environ.get('CHIEF_X', 46.9))
CHIEF_Y = float(os.environ.get('CHIEF_Y', -89.0))
CHIEF_BELOW = float(os.environ.get('CHIEF_BELOW', 1.0))

def flat(a): return np.asarray(a).reshape(-1)

def cstr_array(name, data, ctype='unsigned char', align=64):
    out = ['const %s %s[%d] __attribute__((aligned(%d))) = {' % (ctype, name, len(data), align)]
    line = []
    for i, v in enumerate(data):
        line.append(str(int(v)) if ctype != 'float' else repr(float(v)) + 'f')
        if len(line) == 24:
            out.append(','.join(line) + ','); line = []
    if line: out.append(','.join(line))
    out.append('};')
    return '\n'.join(out) + '\n'

SUN = np.array([0.6, -0.5, 0.7]); SUN /= np.linalg.norm(SUN)

def tint(shader):
    s = shader.lower()
    if 'blood ground' in s: return (0.62, 0.50, 0.34)
    if 'cliff' in s: return (0.52, 0.50, 0.46)
    if 'metal' in s or 'cap_' in s: return (0.45, 0.52, 0.62)
    return (0.8, 0.8, 0.8)

def main():
    mats = load_bsp(MAP)
    P, C, T, base, flipped = [], [], [], 0, 0
    for m in mats:
        v = m['verts']; n = m['normals']
        n = n / np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-9)
        shade = 0.35 + 0.65 * np.clip(np.einsum('ij,j->i', n, SUN), 0, 1)
        col = shade[:, None] * np.array(tint(m['shader']))[None, :]
        tris, nf = oriented(v[:, :3].astype(np.float64), n, m['tris']); flipped += nf
        P.append(v[:, :3]); C.append(np.clip(col, 0, 1) ** (1 / 2.2)); T.append(tris + base)
        base += len(v)
    P = np.concatenate(P).astype(np.float32); C = np.concatenate(C); T = np.concatenate(T)
    assert base < 65536
    rgba = np.zeros((len(P), 4), np.uint8)
    rgba[:, :3] = np.round(C * 255); rgba[:, 3] = 0x80
    z = ground_height(P.astype(np.float64), T, CHIEF_X, CHIEF_Y, 1e9)
    zb = ground_height(P.astype(np.float64), T, CHIEF_X, CHIEF_Y, CHIEF_BELOW)
    print('%d materials, %d verts, %d tris (%d flipped); ground under (%.1f, %.1f): below %.1f -> %s, any -> %s'
          % (len(mats), len(P), len(T), flipped, CHIEF_X, CHIEF_Y, CHIEF_BELOW, zb, z))
    assert zb is not None, 'no ground under the Chief'
    lo, hi = P.min(0), P.max(0)
    os.makedirs(OUT, exist_ok=True)
    c = open(os.path.join(OUT, 'map_assets.c'), 'w')
    c.write('/* generated by tools/export_map.py from the map\'s structure BSP; do not edit */\n#include "map_assets.h"\n\n')
    c.write(cstr_array('map_pos', flat(P), 'float', 16))
    c.write(cstr_array('map_color', flat(rgba), 'unsigned char', 16))
    c.write(cstr_array('map_tri', flat(T.astype(np.uint16)), 'unsigned short', 16))
    c.close()
    h = open(os.path.join(OUT, 'map_assets.h'), 'w')
    h.write('''/* generated by tools/export_map.py; do not edit */
#ifndef MAP_ASSETS_H
#define MAP_ASSETS_H
#define MAP_VERTS %d
#define MAP_TRIS %d
#define MAP_CHIEF_X %rf
#define MAP_CHIEF_Y %rf
#define MAP_CHIEF_Z %rf
extern const float map_pos[];
extern const unsigned char map_color[];
extern const unsigned short map_tri[];
#endif
''' % (len(P), len(T), CHIEF_X, CHIEF_Y, float(zb)))
    h.close()
    print('wrote', os.path.abspath(OUT))

if __name__ == '__main__':
    main()
